export function evaluateAIRecommendation(
  soilMoisture: number,
  rainProbability: number,
  temperature: number,
  cropType: string = 'Tomato'
): AIRecommendation {
  if (soilMoisture < 20) {
    return {
      title: 'AI Recommendation: Immediate Action Required',
      summary: 'Irrigate immediately to prevent irreversible crop stress.',
      actionType: 'irrigate_now',
      delayHours: 0,
      rainProbability,
      currentSoilMoisture: soilMoisture,
      estimatedWaterSavedLiters: 0,
      recommendedWaterAmountLiters: 550,
      recommendedDurationMinutes: 28,
      recommendedStartTime: 'Immediate',
      confidence: 94,
      factors: {
        rainForecast: 15,
        soilMoisture: 55,
        cropRequirement: 20,
        temperature: 10,
      },
      explanationText: `Soil moisture in ${cropType} is at ${soilMoisture}%, which is below the physiological danger threshold of 20%. Even with pending rain forecasts, root transpiration distress requires immediate hydration.`,
      finalSuggestion: 'Initiate emergency irrigation cycle for 28 minutes immediately.',
    };
  }

  if (soilMoisture < 35 && rainProbability >= 70) {
    return {
      title: 'AI Recommendation',
      summary: 'Delay irrigation for approximately 6 hours.',
      actionType: 'delay',
      delayHours: 6,
      rainProbability,
      currentSoilMoisture: soilMoisture,
      estimatedWaterSavedLiters: 320,
      recommendedWaterAmountLiters: 420,
      recommendedDurationMinutes: 21,
      recommendedStartTime: '6:30 PM',
      confidence: 87,
      factors: {
        rainForecast: 40,
        soilMoisture: 35,
        cropRequirement: 15,
        temperature: 10,
      },
      explanationText: 'Rainfall is highly probable within the next six hours. Although soil moisture is below the optimal range, it has not yet reached the critical threshold. Irrigating now may lead to unnecessary water consumption.',
      finalSuggestion: 'Wait 6 hours and reassess soil and weather conditions.',
    };
  }

  if (soilMoisture < 35 && rainProbability < 30) {
    return {
      title: 'AI Recommendation',
      summary: 'Initiate standard scheduled irrigation this afternoon.',
      actionType: 'irrigate_now',
      delayHours: 0,
      rainProbability,
      currentSoilMoisture: soilMoisture,
      estimatedWaterSavedLiters: 90,
      recommendedWaterAmountLiters: 480,
      recommendedDurationMinutes: 24,
      recommendedStartTime: '5:00 PM',
      confidence: 91,
      factors: {
        rainForecast: 10,
        soilMoisture: 50,
        cropRequirement: 25,
        temperature: 15,
      },
      explanationText: `Current moisture of ${soilMoisture}% is dipping without forecasted precipitation replenishment. Irrigating in late afternoon reduces evaporative loss.`,
      finalSuggestion: 'Schedule 24-minute irrigation cycle at 5:00 PM.',
    };
  }

  return {
    title: 'AI Recommendation',
    summary: 'No irrigation required. Optimal soil moisture levels.',
    actionType: 'no_action',
    delayHours: 24,
    rainProbability,
    currentSoilMoisture: soilMoisture,
    estimatedWaterSavedLiters: 450,
    recommendedWaterAmountLiters: 0,
    recommendedDurationMinutes: 0,
    recommendedStartTime: 'Tomorrow 06:00 AM',
    confidence: 92,
    factors: {
      rainForecast: 20,
      soilMoisture: 50,
      cropRequirement: 20,
      temperature: 10,
    },
    explanationText: `Soil moisture at ${soilMoisture}% is in the optimal growth band (40–60%). Root zones have sufficient active water retention.`,
    finalSuggestion: 'Continue continuous sensor monitoring. No action needed.',
  };
}

